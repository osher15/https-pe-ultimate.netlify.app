"use strict";
/* Generates the README section "Correct-form checklists" from the specs (form + doubts). */
const START = "<!-- form:start (generated by src/build.cjs from the specs; edit the specs, not this block) -->";
const END = "<!-- form:end -->";

function viewName(ex) {
  const c = ex.camera || {}, yaw = c.yaw || 0, elev = c.elev || 0;
  let v = yaw === 0 ? "side view" : Math.abs(yaw) >= 85 ? "front view" : "¾ view";
  if (elev) v = "elevated " + v;
  return v;
}
function extras(ex) {
  const out = [];
  if (ex.hold) out.push("hold, stopwatch");
  if (ex.travel) out.push("travels forward, camera follows");
  if (ex.cycles > 1) out.push(`${ex.cycles} repetitions per loop`);
  const props = (ex.props || []).map(p => p.type).concat((ex.held || []).map(h => ({ db: "dumbbells", gdb: "dumbbell", kb: "kettlebell", band: "band", rope: h.ghost ? "imaginary rope" : "jump rope" }[h.type])));
  if (props.length) out.push([...new Set(props)].join(", "));
  return out;
}
function formMarkdown(spec) {
  const lines = [START, ""];
  for (const ex of spec.exercises) {
    lines.push(`**${ex.name} (\`${ex.id}\`, ${viewName(ex)}, ${ex.duration} s${extras(ex).map(x => "; " + x).join("")}).**`);
    for (const f of ex.form || []) lines.push(`- ${f}`);
    for (const d of ex.doubts || []) lines.push(`- *Doubt / limitation:* ${d}`);
    lines.push("");
  }
  lines.push(END);
  return lines.join("\n");
}
function injectReadme(readme, spec) {
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error("README form markers missing");
  return readme.slice(0, a) + formMarkdown(spec) + readme.slice(b + END.length);
}
module.exports = { formMarkdown, injectReadme, START, END };
