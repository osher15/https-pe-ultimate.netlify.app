"use strict";
/* Animations: one cartoon animation + still per exercise id, the single-file build is complete,
   deterministic, under the size budget, offline (data: images only), and nothing couples to the app. */
const test = require("node:test"), assert = require("node:assert/strict");
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const { load, ROOT, TOOL, HTML, HTML_PATH } = require("./_load.cjs");
const B = require("../tools/build-single-file.cjs");
const X = require("../tools/extract-app-data.cjs");
const { D } = load();
const sha = b => crypto.createHash("sha256").update(b).digest("hex");
const SINGLE = fs.readFileSync(B.OUT, "utf8");
const ANIM_DIR = B.ANIM_DIR;
const BUDGET = 2.5 * 1024 * 1024;
const manifest = JSON.parse(fs.readFileSync(path.join(ANIM_DIR, "manifest.json"), "utf8")).items;
const lib = JSON.parse(fs.readFileSync(path.join(ROOT, "store-content", "exercise-anim", "library.json"), "utf8")).exercises;

function animBlock(html) {
  const i = html.indexOf("/*ANIM-START*/"), j = html.indexOf("/*ANIM-END*/");
  assert.ok(i > 0 && j > i, "anim markers");
  return { before: html.slice(0, i), body: html.slice(i + 14, j), after: html.slice(j + 12) };
}
function embedded() {
  const b = animBlock(SINGLE);
  const win = {};
  new Function("window", b.body)(win);
  return win.PE_IT_ANIM;
}

test("every exercise the trainer lists is an exercise of the app (EX list) and has an animation and a still", () => {
  const appIds = Array.from(X.build(ROOT).exercises, e => e.id); /* Array.from: the app data is evaluated in another realm */
  assert.deepEqual(D.exercises.map(e => e.id), appIds, "trainer list = app EX list, same order");
  assert.equal(D.exercises.length, 47);
  assert.deepEqual(lib.map(e => e.anim).sort(), appIds.slice().sort(), "library.json animates exactly the app ids");
  for (const id of appIds) {
    for (const kind of ["svg", "still"]) assert.ok(fs.existsSync(path.join(ANIM_DIR, kind, id + ".svg")), "missing out/" + kind + "/" + id + ".svg");
    assert.equal(sha(fs.readFileSync(path.join(ANIM_DIR, "svg", id + ".svg"))), manifest[id].svgSha256, id + " svg hash");
    assert.equal(sha(fs.readFileSync(path.join(ANIM_DIR, "still", id + ".svg"))), manifest[id].stillSha256, id + " still hash");
  }
});

test("single file embeds all 47 animations (with motion) and stills (without), byte-identical to out/", () => {
  const A = embedded();
  assert.deepEqual(Object.keys(A), D.exercises.map(e => e.id));
  for (const id of Object.keys(A)) {
    assert.equal(A[id].a, fs.readFileSync(path.join(ANIM_DIR, "svg", id + ".svg"), "utf8"), id + " animated");
    assert.equal(A[id].s, fs.readFileSync(path.join(ANIM_DIR, "still", id + ".svg"), "utf8"), id + " still");
    assert.match(A[id].a, /<animate/, id + " animated svg has motion");
    assert.doesNotMatch(A[id].s, /<animate|<set\b|@keyframes/, id + " still has no motion");
    assert.match(A[id].a, /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg"/);
  }
});

test("size budget: single file < 2.5 MB", () => {
  const n = Buffer.byteLength(SINGLE);
  assert.ok(n < BUDGET, n + " B");
  assert.ok(n > 1.2 * 1024 * 1024, "suspiciously small: " + n);
});

test("build is deterministic and the committed file is current", () => {
  const a = B.build().out, b = B.build().out;
  assert.equal(sha(a), sha(b), "two builds are byte-identical");
  assert.equal(SINGLE, a, "interval-trainer.single.html is up to date (run tools/build-single-file.cjs)");
});

test("single file = source + embedded animations + stricter CSP; no other change", () => {
  const s = animBlock(HTML), o = animBlock(SINGLE);
  assert.match(s.body, /^window\.PE_IT_ANIM=null;$/, "source has no embedded media");
  const strip = t => t.replace(/<!-- GENERATED by [^\n]*-->\n/, "").replace("img-src data:;", "img-src 'self' file: data:;");
  assert.equal(strip(o.before) + "/*ANIM-START*/" + s.body + "/*ANIM-END*/" + o.after, HTML, "source reconstructs from the build");
});

test("CSP: data: images only, nothing remote, no blob:/self/file:", () => {
  const csp = /http-equiv="Content-Security-Policy" content="([^"]+)"/.exec(SINGLE)[1];
  assert.equal(csp, "default-src 'none'; img-src data:; style-src 'unsafe-inline'; script-src 'unsafe-inline'; base-uri 'none'; form-action 'none'");
  assert.ok(!/blob:|'self'|file:|https?:|connect-src/.test(csp));
});

test("no references to the old GIFs, media folder or app media; no network or app coupling (source and built, minus the SVG block)", () => {
  const builtNoAnim = (() => { const o = animBlock(SINGLE); return o.before + o.after; })();
  const forbidden = [/peultimate/i, /PE Ultimate/, /stu\.list/, /\broster\b/i, /\bSESSION\b/, /window\.FT\b/, /\bSTU\./, /\bHMDATA\b/, /grades?\./,
    /\bcid\b/, /\bsid\b/, /https?:\/\//, /\bfetch\(/, /XMLHttpRequest/, /WebSocket/, /sendBeacon/, /EventSource/, /\bimport\(/, /<link\b/, /@import/, /url\(/, /<iframe/i, /ytUrl|youtube/i,
    /media\/|\.gif\b|exercise-gifs|photo\//];
  for (const [name, txt] of [["source", HTML], ["built", builtNoAnim]]) {
    for (const re of forbidden) assert.ok(!re.test(txt), name + " forbidden: " + re);
  }
  const keys = [...HTML.matchAll(/["']([a-z][\w.-]*\.v\d)["']/g)].map(m => m[1]);
  assert.deepEqual([...new Set(keys)], ["pe-tools.interval-trainer.v1"], "one own storage key");
  assert.equal((HTML.match(/localStorage/g) || []).length, 1, "storage is accessed only through the store adapter");
  /* the SVGs themselves load nothing: the only absolute URL allowed is the SVG namespace */
  for (const [id, v] of Object.entries(embedded())) for (const k of ["a", "s"]) {
    const urls = (v[k].match(/https?:\/\/[^"'\s)]+/g) || []).filter(u => u !== "http://www.w3.org/2000/svg");
    assert.deepEqual(urls, [], id + " svg external url");
    assert.doesNotMatch(v[k], /<image\b|<script|<foreignObject|xlink:href|\bhref="(?!#)|@import/i, id + " svg pulls no resource");
  }
});

test("the old media/ GIF folder is gone and the README no longer ships it", () => {
  assert.ok(!fs.existsSync(path.join(TOOL, "media")), "media/ removed");
  const readme = fs.readFileSync(path.join(TOOL, "README.md"), "utf8");
  assert.ok(readme.includes("interval-trainer.single.html"));
});
