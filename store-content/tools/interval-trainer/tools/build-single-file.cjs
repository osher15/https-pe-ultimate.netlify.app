#!/usr/bin/env node
"use strict";
/*
 * Builds the self-contained offline deliverable interval-trainer.single.html from the readable
 * source interval-trainer.html (the source of truth) plus the cartoon animations in
 * store-content/exercise-anim/out/{svg,still}.
 *
 *   node store-content/tools/interval-trainer/tools/build-single-file.cjs          # write
 *   node store-content/tools/interval-trainer/tools/build-single-file.cjs --check  # exit 1 if stale
 *
 * Deterministic: no timestamps, no randomness, exercises in the source's order, the SVG bytes are
 * embedded unchanged. Fails when an exercise has no animation or still, or when a file does not match
 * the SHA-256 in exercise-anim/out/manifest.json. Edits to the page go into the source file only.
 */
const fs = require("fs"), path = require("path"), crypto = require("crypto");

const TOOL = path.resolve(__dirname, "..");
const ANIM_DIR = path.resolve(TOOL, "..", "..", "exercise-anim", "out");
const SRC = path.join(TOOL, "interval-trainer.html");
const OUT = path.join(TOOL, "interval-trainer.single.html");
const CSP_SRC = "img-src 'self' file: data:;";
const CSP_OUT = "img-src data:;";
const sha = b => crypto.createHash("sha256").update(b).digest("hex");

function exerciseIds(html) {
  const m = /<script id="pe-it-data">([\s\S]*?)<\/script>/.exec(html);
  if (!m) throw new Error("data script not found");
  const win = {};
  new Function("window", m[1])(win);
  return win.PE_IT_DATA.exercises.map(e => e.id);
}

function build() {
  const html = fs.readFileSync(SRC, "utf8");
  const manifest = JSON.parse(fs.readFileSync(path.join(ANIM_DIR, "manifest.json"), "utf8")).items;
  const ids = exerciseIds(html);
  const anim = {}, problems = [];
  for (const id of ids) {
    const fa = path.join(ANIM_DIR, "svg", id + ".svg"), fst = path.join(ANIM_DIR, "still", id + ".svg");
    if (!fs.existsSync(fa) || !fs.existsSync(fst)) { problems.push(id + ": missing animation or still"); continue; }
    const a = fs.readFileSync(fa), s = fs.readFileSync(fst), mi = manifest[id];
    if (!mi) { problems.push(id + ": not in manifest.json"); continue; }
    if (sha(a) !== mi.svgSha256) problems.push(id + ": animated svg differs from manifest");
    if (sha(s) !== mi.stillSha256) problems.push(id + ": still svg differs from manifest");
    const at = a.toString("utf8"), st = s.toString("utf8");
    for (const t of [at, st]) if (/<script/i.test(t) || /<\/script/i.test(t) || /(?:href|src)\s*=\s*["']\s*(?:https?:|\/\/)/i.test(t)) problems.push(id + ": unsafe content");
    anim[id] = { a: at, s: st };
  }
  if (problems.length) throw new Error("cannot build:\n  " + problems.join("\n  "));

  const START = "/*ANIM-START*/", END = "/*ANIM-END*/";
  const i = html.indexOf(START), j = html.indexOf(END);
  if (i < 0 || j < i || html.indexOf(START, i + 1) >= 0) throw new Error("ANIM markers not found exactly once");
  if (html.split(CSP_SRC).length !== 2) throw new Error("source CSP img-src clause not found exactly once");
  const block = START + "window.PE_IT_ANIM=" + JSON.stringify(anim) + ";" + END;
  let out = html.slice(0, i) + block + html.slice(j + END.length);
  out = out.replace(CSP_SRC, CSP_OUT);
  const T = "<title>Interval Trainer · PE Tools</title>";
  if (out.split(T).length !== 2) throw new Error("title not found exactly once");
  out = out.replace(T, T + "\n<!-- GENERATED by tools/build-single-file.cjs from interval-trainer.html. Do not edit; edit the source and rebuild. -->");
  return { out, ids: ids.length };
}

if (require.main === module) {
  const { out, ids } = build();
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if (cur !== out) { console.error("interval-trainer.single.html is stale; run the build script"); process.exit(1); }
    console.log("single file up to date (" + Buffer.byteLength(out) + " B, " + ids + " exercises)");
  } else {
    fs.writeFileSync(OUT, out);
    console.log("wrote " + path.relative(process.cwd(), OUT) + ": " + Buffer.byteLength(out) + " B, " + ids + " exercises with animation + still");
  }
}
module.exports = { build, OUT, SRC, ANIM_DIR };
